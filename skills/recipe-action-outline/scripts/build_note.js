#!/usr/bin/env node
// Turns a recipe body fragment into an Obsidian note plus a CSS snippet.
// Usage: node build_note.js body.html out.md [--title "Recipe name"] [--snippet out.css]
//   out.md   YAML frontmatter, a "# title" heading, then one HTML block (<div class="ao">) with the
//            legend, tables and note cards. No blank lines inside it, because a blank line ends an
//            HTML block in Markdown. Obsidian strips <style> tags from notes, so styling is NOT in
//            the note.
//   out.css  (with --snippet) assets/outline.css scoped under .ao and the Obsidian reading view, so
//            nothing leaks into Obsidian's own UI. Light and dark follow Obsidian's theme classes
//            (.theme-light, .theme-dark). Install once as <vault>/.obsidian/snippets/action-outline.css
//            and enable it under Settings > Appearance > CSS snippets.
// After writing, runs check_grid.js on out.md and exits with its status.
const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');

const args = process.argv.slice(2);
const titleAt = args.indexOf('--title');
const titleArg = titleAt >= 0 ? args.splice(titleAt, 2)[1] : null;
const snipAt = args.indexOf('--snippet');
const snippetFile = snipAt >= 0 ? args.splice(snipAt, 2)[1] : null;
const [bodyFile, outFile] = args;
if (!bodyFile || !outFile) {
  console.error('Usage: node build_note.js body.html out.md [--title "Recipe name"] [--snippet out.css]');
  process.exit(2);
}

const root = path.join(__dirname, '..');
const rawCss = fs.readFileSync(path.join(root, 'assets', 'outline.css'), 'utf8').replace(/\/\*[\s\S]*?\*\//g, '');
let body = fs.readFileSync(bodyFile, 'utf8');

// Split the stylesheet into top-level rules.
const rules = [];
{
  let depth = 0, start = 0, preludeEnd = 0;
  for (let i = 0; i < rawCss.length; i++) {
    const ch = rawCss[i];
    if (ch === '{') { if (depth === 0) preludeEnd = i; depth++; }
    else if (ch === '}') {
      depth--;
      if (depth === 0) {
        rules.push({ sel: rawCss.slice(start, preludeEnd).trim(), body: rawCss.slice(preludeEnd + 1, i).trim() });
        start = i + 1;
      }
    }
  }
}

const flat = (decls) => decls.replace(/\s+/g, ' ').trim();
const lightTokens = rules.find((r) => r.sel === ':root');
const darkTokens = rules.find((r) => r.sel === ':root[data-theme="dark"]');
if (!lightTokens || !darkTokens) {
  console.error('assets/outline.css: expected a bare :root block and a :root[data-theme="dark"] block');
  process.exit(1);
}
const fontOverride = '--font: var(--font-text, system-ui, sans-serif); --mono: var(--font-monospace, ui-monospace, monospace);';

const out = [];
out.push(`.ao { ${flat(lightTokens.body).replace(/--font:[^;]*;|--mono:[^;]*;/g, '')} ${fontOverride} background: var(--bg); color: var(--fg); font-family: var(--font); font-size: 15px; line-height: 1.45; padding: 14px; border-radius: 10px; color-scheme: light; }`);
out.push(`.theme-dark .ao { ${flat(darkTokens.body).replace(/color-scheme:[^;]*;?/, '')} color-scheme: dark; }`);
for (const r of rules) {
  if (r.sel === ':root' || r.sel === ':root[data-theme="dark"]' || r.sel.startsWith('@media')) continue;
  if (r.sel === 'body') continue;
  const sel = r.sel.split(',').map((s) => `:is(.markdown-rendered, .markdown-source-view) .ao ${s.trim()}`).join(', ');
  out.push(`${sel} { ${flat(r.body)} }`);
}
const css = '/* Action outline recipes. Generated by recipe-action-outline/scripts/build_note.js. */\n' + out.join('\n') + '\n';

// Body: drop the page header (the note title replaces it), main -> div, no blank lines.
const h1 = body.match(/<h1[^>]*>([\s\S]*?)<\/h1>/i);
const title = titleArg || (h1 ? h1[1].replace(/<[^>]+>/g, '').trim() : 'Recipe');
body = body.replace(/<header>[\s\S]*?<\/header>/i, '').replace(/<main/g, '<div').replace(/<\/main>/g, '</div>');
const html = body.split('\n').map((l) => l.trim()).filter(Boolean).join('\n');

const note = `---
tags: [cooking]
---
# ${title}

<div class="ao">
${html}
</div>
`;
fs.writeFileSync(outFile, note);
if (snippetFile) fs.writeFileSync(snippetFile, css);
console.log(`wrote ${outFile} (${title})`);

const check = spawnSync(process.execPath, [path.join(__dirname, 'check_grid.js'), outFile], { stdio: 'inherit' });
process.exit(check.status === null ? 1 : check.status);
